#!/usr/bin/env python3
"""Convert a codex-pet spritesheet (8 cols x 9 rows) into an RGB565 frame blob
plus a C header describing the nine animation states.

Usage: python gen_pet_frames.py <spritesheet.webp> <out_dir>
"""
import sys
from pathlib import Path

import numpy as np
from PIL import Image

CW, CH = 192, 208          # spritesheet cell size
FRAME_H = 128
BG_COLOR = (0, 0, 0)  # match the dark theme background
FRAME_W = round(88 * FRAME_H / 128)  # keep the source aspect ratio
# Rotate each frame on the host instead of rotating the panel: panel-level
# swap_xy left coloured artefacts along the edges of this 128x128 panel.
ROTATE_DEG = 90
# Mirror the finished frame left-to-right. The shipped pet_frames.bin is
# mirrored: the picture on the panel is a reflection of the original art (the
# device sits behind a beam splitter), so the frames are flipped to compensate.
MIRROR_X = True
OUT_W, OUT_H = (FRAME_H, FRAME_W) if ROTATE_DEG in (90, 270) else (FRAME_W, FRAME_H)
STATE_COUNTS = [6, 8, 8, 4, 5, 8, 6, 6, 6]
STATE_NAMES = [
    "idle", "run_right", "run_left", "wave", "jump",
    "fail", "wait", "review", "run",
]


def load_mask(im: Image.Image) -> np.ndarray:
    a = np.array(im)
    alpha = a[:, :, 3]
    rgb = a[:, :, :3]
    return ~(((rgb > 245).all(axis=2)) | (alpha < 10))


def state_bbox(mask: np.ndarray, row: int, count: int):
    """Union bbox over the whole row so frames share one crop window."""
    x0 = y0 = 10 ** 9
    x1 = y1 = -1
    for c in range(count):
        sub = mask[row * CH:(row + 1) * CH, c * CW:(c + 1) * CW]
        ys, xs = np.where(sub)
        if not len(xs):
            continue
        x0, x1 = min(x0, xs.min()), max(x1, xs.max())
        y0, y1 = min(y0, ys.min()), max(y1, ys.max())
    return int(x0), int(y0), int(x1), int(y1)


def main() -> None:
    src = Path(sys.argv[1])
    out = Path(sys.argv[2])
    out.mkdir(parents=True, exist_ok=True)

    im = Image.open(src).convert("RGBA")
    mask = load_mask(im)

    blob = bytearray()
    index = []
    for row, count in enumerate(STATE_COUNTS):
        x0, y0, x1, y1 = state_bbox(mask, row, count)
        w, h = x1 - x0 + 1, y1 - y0 + 1
        for c in range(count):
            frame = im.crop(
                (c * CW + x0, row * CH + y0, c * CW + x1 + 1, row * CH + y1 + 1)
            ).resize((FRAME_W, FRAME_H), Image.LANCZOS)
            canvas = Image.new("RGB", (FRAME_W, FRAME_H), BG_COLOR)
            nw = max(1, round(w * FRAME_H / h))
            scaled = frame.resize((nw, FRAME_H), Image.LANCZOS)
            canvas.paste(scaled, ((FRAME_W - nw) // 2, 0), scaled)
            if ROTATE_DEG:
                canvas = canvas.rotate(ROTATE_DEG, expand=True)
            if MIRROR_X:
                canvas = canvas.transpose(Image.FLIP_LEFT_RIGHT)
            arr = np.asarray(canvas, dtype=np.uint16)
            r = (arr[:, :, 0] >> 3) & 0x1F
            g = (arr[:, :, 1] >> 2) & 0x3F
            b = (arr[:, :, 2] >> 3) & 0x1F
            rgb565 = (r << 11) | (g << 5) | b
            blob += rgb565.astype("<u2").tobytes()
        index.append((row, count, len(blob)))

    (out / "pet_frames.bin").write_bytes(blob)

    total = OUT_W * OUT_H * 2
    lines = [
        "// generated by gen_pet_frames.py -- do not edit",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define PET_FRAME_W {OUT_W}",
        f"#define PET_FRAME_H {OUT_H}",
        f"#define PET_FRAME_BYTES {total}",
        f"#define PET_FRAME_COUNT {sum(STATE_COUNTS)}",
        f"#define PET_STATE_COUNT {len(STATE_COUNTS)}",
        "",
        "static const uint16_t pet_state_first[PET_STATE_COUNT] = {"
        + ", ".join(str(sum(STATE_COUNTS[:i])) for i in range(len(STATE_COUNTS)))
        + "};",
        "static const uint8_t pet_state_frames[PET_STATE_COUNT] = {"
        + ", ".join(str(c) for c in STATE_COUNTS)
        + "};",
        "static const char* const pet_state_names[PET_STATE_COUNT] = {"
        + ", ".join(f'"{n}"' for n in STATE_NAMES)
        + "};",
        "",
    ]
    (out / "pet_frames.h").write_text("\n".join(lines), encoding="utf-8")
    print(f"blob {len(blob)} bytes, frames {sum(STATE_COUNTS)}")


if __name__ == "__main__":
    main()
